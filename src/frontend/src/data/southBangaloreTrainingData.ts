// ─── Helper for carpet records ───────────────────────────────────────────────
const SBA_FACTOR = 1.36;

function apt(
  locality: string,
  builder: string,
  project: string,
  areaSqft: number,
  areaType: "SBA" | "Carpet",
  soldPrice: number,
  year: number,
  flags?: Partial<
    Omit<
      SouthBangaloreRecord,
      | "locality"
      | "builder"
      | "project"
      | "areaSqft"
      | "areaType"
      | "soldPrice"
      | "year"
      | "region"
    >
  >,
): SouthBangaloreRecord {
  const rec: SouthBangaloreRecord = {
    locality,
    builder,
    project,
    areaSqft,
    areaType,
    soldPrice,
    year,
    region: "south",
    ...flags,
  };
  if (areaType === "Carpet") {
    rec.isCarpet = true;
    rec.normalizedAreaSqft = Math.round(areaSqft * SBA_FACTOR);
  }
  return rec;
}

