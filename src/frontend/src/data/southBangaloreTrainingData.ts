// ─── Utility: get effective area (SBA-normalized) ────────────────────────────
export function getEffectiveArea(record: SouthBangaloreRecord): number {
  return record.isCarpet && record.normalizedAreaSqft
    ? record.normalizedAreaSqft
    : record.areaSqft;
}

// ─── Utility: get price per effective sqft ──────────────────────────────────
export function getPSF(record: SouthBangaloreRecord): number {
  const area = getEffectiveArea(record);
  return area > 0 ? Math.round(record.soldPrice / area) : 0;
}

