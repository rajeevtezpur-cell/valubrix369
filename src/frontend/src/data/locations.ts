export function searchLocations(
  query: string,
): Array<{ city: string; locality: string; display: string }> {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase().replace(/\s+/g, " ").trim();
  const results: Array<{ city: string; locality: string; display: string }> =
    [];

  for (const [city, localities] of Object.entries(LOCALITIES_BY_CITY)) {
    // Check city match
    if (city.toLowerCase().includes(q)) {
      results.push({ city, locality: "", display: `${city}` });
    }
    // Check locality match
    for (const locality of localities) {
      if (locality.toLowerCase().includes(q)) {
        results.push({ city, locality, display: `${locality}, ${city}` });
      }
    }
  }

  return results.slice(0, 8);
}
