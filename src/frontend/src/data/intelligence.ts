export function formatPrice(priceInr: number): string {
  if (priceInr >= 10000000) {
    return `₹${(priceInr / 10000000).toFixed(2)} Cr`;
  }
  if (priceInr >= 100000) {
    return `₹${(priceInr / 100000).toFixed(1)} L`;
  }
  return `₹${priceInr.toLocaleString("en-IN")}`;
}

export function formatPriceRange(base: number, variance = 0.1): string {
  const low = Math.round(base * (1 - variance));
  const high = Math.round(base * (1 + variance));
  return `${formatPrice(low)} – ${formatPrice(high)}`;
}

export const PRICE_TREND_YEARS = ["2022", "2023", "2024", "2025", "2026"];

export function generatePriceTrend(
  currentPrice: number,
  growthRate: number,
): Array<{ year: string; price: number }> {
  const annualGrowth = growthRate / 100;
  const prices: Array<{ year: string; price: number }> = [];
  let price = currentPrice;
  // Work backwards from 2026
  for (let i = 4; i >= 0; i--) {
    prices.unshift({ year: PRICE_TREND_YEARS[i], price: Math.round(price) });
    price = price / (1 + annualGrowth);
  }
  return prices;
}

