// ─── Utility functions ────────────────────────────────────────────────────────

/**
 * Lookup a micro-location by name (case-insensitive, partial match allowed).
 */
export function getMicroLocationByName(
  name: string,
): MicroLocation | undefined {
  if (!name) return undefined;
  const lower = name.toLowerCase().trim();
  let found = bangaloreMicroLocations.find(
    (l) => l.name.toLowerCase() === lower,
  );
  if (found) return found;
  found = bangaloreMicroLocations.find(
    (l) =>
      l.name.toLowerCase().includes(lower) ||
      lower.includes(l.name.toLowerCase()),
  );
  return found;
}

/**
 * Get the correct pincode for a locality name.
 * Returns empty string "" if not found — never returns a default PIN.
 */
export function getPincodeForLocality(name: string): string {
  const loc = getMicroLocationByName(name);
  return loc?.pincode ?? "";
}

/**
 * Get all locations grouped by zone.
 */
export function getLocationsByZone(): Record<string, MicroLocation[]> {
  const groups: Record<string, MicroLocation[]> = {
    North: [],
    East: [],
    South: [],
    West: [],
    Central: [],
  };
  for (const loc of bangaloreMicroLocations) {
    groups[loc.zone].push(loc);
  }
  return groups;
}

/**
 * Returns all locations with popular ones first.
 */
export function getOrderedLocations(): MicroLocation[] {
  const popular = bangaloreMicroLocations.filter((l) => l.isPopular);
  const rest = bangaloreMicroLocations.filter((l) => !l.isPopular);
  return [...popular, ...rest];
}

/**
 * Search micro-locations by query string (name or parentArea).
 * Returns up to `limit` matches sorted by popularity.
 */
export function searchMicroLocations(
  query: string,
  limit = 10,
): MicroLocation[] {
  if (!query || query.trim().length < 2)
    return getOrderedLocations().slice(0, limit);
  const lower = query.toLowerCase().trim();
  const results = bangaloreMicroLocations.filter(
    (l) =>
      l.name.toLowerCase().includes(lower) ||
      l.parentArea.toLowerCase().includes(lower),
  );
  const popularityOrder = { high: 0, medium: 1, low: 2 };
  results.sort(
    (a, b) =>
      (popularityOrder[a.popularity ?? "low"] ?? 2) -
      (popularityOrder[b.popularity ?? "low"] ?? 2),
  );
  return results.slice(0, limit);
}

/**
 * Get all location names as a flat sorted array for autocomplete.
 */
export function getAllLocationNames(): string[] {
  return bangaloreMicroLocations
    .map((l) => l.name)
    .sort((a, b) => a.localeCompare(b));
}

/**
 * getZoneLabelForLocality — look up the zone label for a location name.
 *
 * Uses bangaloreMicroLocations data first (has stored zoneLabel/parentArea).
 * Falls back to re-exporting localityEngine's getLocalityZoneLabel.
 *
 * This is the function all portals should call when displaying the zone
 * of a user-selected location — no reverse geocoding needed.
 *
 * @param name  Location name from the dropdown (case-insensitive)
 * @returns     Human-readable zone label, never "Unknown"
 */
export function getZoneLabelForLocality(name: string): string {
  const lower = name.toLowerCase().trim();
  // Exact name match
  let loc = bangaloreMicroLocations.find((l) => l.name.toLowerCase() === lower);
  // Partial match
  if (!loc) {
    loc = bangaloreMicroLocations.find(
      (l) =>
        l.name.toLowerCase().includes(lower) ||
        lower.includes(l.name.toLowerCase()),
    );
  }
  if (loc) {
    if (loc.zoneLabel) return loc.zoneLabel;
    // Map enum zone to readable label
    const zoneMap: Record<string, string> = {
      North: "North Bangalore",
      South: "South Bangalore",
      East: "East Bangalore",
      West: "West Bangalore",
      Central: "Central Bangalore",
    };
    return zoneMap[loc.zone] ?? loc.parentArea ?? "Bangalore";
  }
  // No match in local data — return generic
  return "Bangalore";
}
