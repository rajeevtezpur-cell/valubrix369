/**
 * Returns coordinates for a locality name.
 * Tries exact match first, then fuzzy substring match.
 * Returns null if genuinely unknown.
 */
export function getCoords(
  localityName: string,
): { lat: number; lng: number } | null {
  const key = localityName.toLowerCase().trim();
  if (ALL_LOCALITY_COORDS[key]) return ALL_LOCALITY_COORDS[key];
  for (const [k, v] of Object.entries(ALL_LOCALITY_COORDS)) {
    if (key.includes(k) || k.includes(key)) return v;
  }
  return null;
}
